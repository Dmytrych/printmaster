import { test } from "node:test";
import * as assert from "node:assert/strict";
import * as cdk from "aws-cdk-lib";
import { Match, Template } from "aws-cdk-lib/assertions";
import { DataStack } from "../lib/data-stack.js";

const app = new cdk.App();
const stack = new DataStack(app, "TestDataStack", {
  env: { account: "123456789012", region: "eu-central-1" },
  removalPolicy: cdk.RemovalPolicy.DESTROY,
  deletionProtection: false,
});
const template = Template.fromStack(stack);

test("spools table logical ID is stable (changing it would replace the table and lose data)", () => {
  const tables = Object.keys(template.findResources("AWS::DynamoDB::GlobalTable"));
  assert.deepEqual(tables, ["FilamentSpoolsTable615771BD"]);
});

test("spools table uses generic PK/SK string keys", () => {
  template.hasResourceProperties("AWS::DynamoDB::GlobalTable", {
    KeySchema: [
      { AttributeName: "PK", KeyType: "HASH" },
      { AttributeName: "SK", KeyType: "RANGE" },
    ],
    AttributeDefinitions: [
      { AttributeName: "PK", AttributeType: "S" },
      { AttributeName: "SK", AttributeType: "S" },
    ],
  });
});

test("table name is generated by CloudFormation, not hardcoded", () => {
  template.hasResourceProperties("AWS::DynamoDB::GlobalTable", { TableName: Match.absent() });
});

test("on-demand billing and no point-in-time recovery (cost)", () => {
  template.hasResourceProperties("AWS::DynamoDB::GlobalTable", {
    BillingMode: "PAY_PER_REQUEST",
    Replicas: [
      Match.objectLike({ PointInTimeRecoverySpecification: { PointInTimeRecoveryEnabled: false } }),
    ],
  });
});

test("removal policy comes from props", () => {
  template.hasResource("AWS::DynamoDB::GlobalTable", { DeletionPolicy: "Delete" });

  const prodApp = new cdk.App();
  const prod = new DataStack(prodApp, "ProdDataStack", {
    env: { account: "123456789012", region: "eu-central-1" },
    removalPolicy: cdk.RemovalPolicy.RETAIN,
    deletionProtection: true,
  });
  const prodTemplate = Template.fromStack(prod);
  prodTemplate.hasResource("AWS::DynamoDB::GlobalTable", { DeletionPolicy: "Retain" });
  prodTemplate.hasResourceProperties("AWS::DynamoDB::GlobalTable", {
    Replicas: [Match.objectLike({ DeletionProtectionEnabled: true })],
  });
});
